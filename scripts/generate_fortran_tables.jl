# Extract the DATA tables of the Fortran reference into Julia source files.
#
#   julia scripts/generate_fortran_tables.jl
#
# Writes src/native/tables/pwnodes.jl and src/native/tables/sognodes.jl.

const ROOT = normpath(joinpath(@__DIR__, ".."))
const FSRC = joinpath(ROOT, "deps", "boxdmk_fortran", "src", "bdmk")
const OUTDIR = joinpath(ROOT, "src", "native", "tables")

# Join fixed-form continuation lines and drop comments.
function logical_lines(path)
    out = String[]
    for raw in eachline(path)
        isempty(raw) && continue
        c = raw[1]
        (c == 'c' || c == 'C' || c == '*' || c == '!') && continue
        if length(raw) >= 6 && raw[6] != ' ' && !isempty(out) && strip(raw[1:5]) == ""
            out[end] *= raw[7:end]
        else
            push!(out, raw)
        end
    end
    return out
end

# Returns Dict(subroutine => Dict(name => values)).
function parse_data(path)
    tables = Dict{String,Dict{String,Vector{Float64}}}()
    current = ""
    for line in logical_lines(path)
        m = match(r"^\s*subroutine\s+(\w+)"i, line)
        if m !== nothing
            current = lowercase(m.captures[1])
            tables[current] = Dict{String,Vector{Float64}}()
            continue
        end
        for d in eachmatch(r"data\s+(\w+)\s*/([^/]*)/"i, line)
            name = lowercase(d.captures[1])
            body = replace(d.captures[2], r"[dD]" => "e")
            vals = [parse(Float64, strip(s)) for s in split(body, ',') if !isempty(strip(s))]
            tables[current][name] = vals
        end
    end
    return tables
end

fmt(v) = "[" * join((repr(x) for x in v), ", ") * "]"

function write_pwnodes()
    t = parse_data(joinpath(FSRC, "bdmk_pwterms.f"))
    io = IOBuffer()
    println(io, "# AUTO-GENERATED by scripts/generate_fortran_tables.jl from bdmk_pwterms.f. Do not edit.")
    println(io, "# PW_NPW0[digits][ilev+11] for ilev in -10:0; PW_NODES[(digits, ilev)] = (ts, ws) half-line data.")
    println(io, "const PW_NPW0 = Dict{Int,Vector{Int}}(")
    for d in 2:11
        npw0 = Int.(t["dmkpwterms_md$d"]["npw0"])
        println(io, "    $d => ", fmt(npw0), ",")
    end
    println(io, ")")
    println(io, "const PW_NODES = Dict{Tuple{Int,Int},Tuple{Vector{Float64},Vector{Float64}}}(")
    for d in 2:11
        sub = t["get_pwnodes_md$d"]
        for ilev in -10:0
            suffix = ilev == 0 ? "0" : "m$(-ilev)"
            println(io, "    ($d, $ilev) => (", fmt(sub["ts"*suffix]), ", ", fmt(sub["ws"*suffix]), "),")
        end
    end
    println(io, ")")
    write(joinpath(OUTDIR, "pwnodes.jl"), take!(io))
end

function write_sognodes()
    io = IOBuffer()
    println(io, "# AUTO-GENERATED by scripts/generate_fortran_tables.jl from sogapproximation/*.f. Do not edit.")
    println(io, "# SOG_TABLES[name][k] = (ts, ws) for precision band k = 1:4 (3/6/9/12 digits).")
    println(io, "const SOG_TABLES = Dict{Symbol,Vector{Tuple{Vector{Float64},Vector{Float64}}}}(")
    for (name, tsname) in (("l3dsognodes", "ts"), ("sl3dsognodes", "ts"), ("l2dsognodes", "xs"))
        sub = parse_data(joinpath(FSRC, "sogapproximation", name * ".f"))[name]
        println(io, "    :$name => [")
        for k in 0:3
            println(io, "        (", fmt(sub["$tsname$k"]), ", ", fmt(sub["ws$k"]), "),")
        end
        println(io, "    ],")
    end
    println(io, ")")
    write(joinpath(OUTDIR, "sognodes.jl"), take!(io))
end

mkpath(OUTDIR)
write_pwnodes()
write_sognodes()
println("wrote tables to $OUTDIR")
